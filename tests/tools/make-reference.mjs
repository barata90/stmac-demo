/* Build the solver fixture and reference numbers from the ORIGINAL single-file page.
 *
 * Usage (from tests/):
 *   git show 473edc3:index.html > /tmp/stmac-single-file.html
 *   node tools/make-reference.mjs /tmp/stmac-single-file.html
 *
 * The inline solver of that page is copied unchanged except for three small, documented
 * patches that align it with the final paper (listed in PATCHES below). The result is written
 * to reference/single-file-solver.js, which the differential tests run next to the refactored
 * assets/js/stmac-core.js in the same engine. The same patched code, evaluated here, produces
 * reference/solver-reference.json: for each scenario the five RMSEs, the unknown count, the
 * half-bandwidth, the effective missing fraction and a sampled checksum over every
 * reconstruction array. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { TESTS_DIR, reconChecksum } from '../helpers.mjs';

/* [why, exact text in the single-file solver, replacement]; each must match exactly once */
const PATCHES = [
  ['Section III-B: the longitude-sheaf shift is measured from the network-mean longitude (the single-file page used the UTC+3 meridian, 45 E; relative shifts between stations are the same, so reconstructions do not change)',
    'const del=STATIONS.map(s=>Math.round((s.lon/15-TZ)*12));',
    'const LM=STATIONS.reduce((a,s)=>a+s.lon,0)/STATIONS.length;const del=STATIONS.map(s=>Math.round((s.lon-LM)/15*12));'],
  ['Section V-A and the notebooks\' DAYTIME mask: RMSE over unobserved cells at clock hours 8 to 16 (the single-file page used clear-sky GHI > 20 W/m2)',
    'if(!M[v][i]&&CS[v][i]>20){const d=rec[v][i]-truth[v][i];s+=d*d;c++;}',
    '{const h=Math.floor((i%SPD)*5/60);if(!M[v][i]&&h>=8&&h<=16){const d=rec[v][i]-truth[v][i];s+=d*d;c++;}}'],
  ['Sections IV-B and V-C: optional zero prior, for the ablation S0 (C = 0, g = 0, r = 10)',
    'function stmacJoint(Z,M,Lg,r,g,useShift,halfWin){',
    'function stmacJoint(Z,M,Lg,r,g,useShift,halfWin,noPrior){'],
  ['Sections IV-B and V-C: optional zero prior, for the ablation S0 (continued)',
    'const C=mdvPrior(Z,M,halfWin);',
    'const C=noPrior?STATIONS.map(()=>new Float64Array(T)):mdvPrior(Z,M,halfWin);']];

const src = process.argv[2];
if (!src) { console.error('usage: node tools/make-reference.mjs <single-file index.html>'); process.exit(2); }
const html = fs.readFileSync(src, 'utf8');
const js = html.split('<script>')[1].split('</script>')[0];
const a = js.indexOf('/* ================= real 1999 NLR payload');
const b = js.indexOf('/* ================= state ================= */');
if (a < 0 || b < 0) { console.error('could not find the solver section in ' + src); process.exit(1); }
let solver = js.slice(a, b);
for (const [why, from, to] of PATCHES) {
  const n = solver.split(from).length - 1;
  if (n !== 1) { console.error('patch matched ' + n + ' times: ' + why); process.exit(1); }
  solver = solver.replace(from, to);
}
const payloadRaw = Buffer.from(solver.match(/const REAL_B64='([^']*)'/)[1], 'base64');
const dataSha256 = crypto.createHash('sha256').update(payloadRaw).digest('hex');
solver = solver.replace(/const REAL_B64='[^']*';/, '/* REAL_B64 removed: the tests feed the decoded assets/data/nlr1999.js, whose sha256 matches this payload */');

const helpersSrc = `
function computeCS(){const CS=[];for(let v=0;v<N;v++){const cs=new Float64Array(T);for(let i=0;i<T;i++)cs[i]=clearSky(v,i);CS.push(cs);}return CS;}
function setReal(){DAYS=REALMETA.DAYS;T=SPD*DAYS;DOY0=REALMETA.DOY0;START_UTC=REALMETA.START;}
function setSyn(){DAYS=SYN.DAYS;T=SPD*DAYS;DOY0=SYN.DOY0;START_UTC=SYN.START;}
return {buildGraph,buildBlockMask,pureTemporal,stmacJoint,climFill,rmseMasked,genData,computeCS,setReal,setSyn,BLOCKS,MDV_WIN,AT,N,get T(){return T;}};
`;
const fixture = '/* Solver section of the single-file index.html at commit 473edc3, generated by tools/make-reference.mjs.\n' +
  ' * Do not edit. Unchanged except for these patches, which align it with the final paper:\n' +
  PATCHES.map(p => ' *  - ' + p[0] + '\n').join('') +
  ' * This is the behaviour the refactored assets/js/stmac-core.js must reproduce bit for bit. */\n' +
  'function makeSingleFileSolver(){\n\'use strict\';\n' + solver + helpersSrc + '}\n';
fs.writeFileSync(path.join(TESTS_DIR, 'reference/single-file-solver.js'), fixture);

/* evaluate the fixture and record the reference */
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fixture + '\nthis.__B = makeSingleFileSolver();', ctx);
const B = ctx.__B;
const { Lg } = B.buildGraph();
function decode() { const U = []; const Tr = 70 * 288; for (let v = 0; v < B.N; v++) { const u = new Float64Array(Tr); for (let i = 0; i < Tr; i++) u[i] = payloadRaw.readInt16LE((v * Tr + i) * 2); U.push(u); } return U; }

/* kind, seed (synthetic weather), block index, outage fraction, mask seed, r, g */
const SCENARIOS = [
  ...[0, 1, 2, 3, 4, 5, 6].map(k => ['real', 42, k, 0.10, 11, 1000, 3]),  /* page defaults, every block length */
  ['real', 42, 2, 0.05, 7930, 100, 0],
  ['real', 42, 6, 0.15, 11, 10000, 30],
  ['real', 42, 0, 0.15, 99, 10, 0],
  ['real', 42, 3, 0.05, 12345, 10000, 30],
  ['syn', 42, 3, 0.10, 11, 1000, 3],
  ['syn', 1013904265, 5, 0.12, 7930, 10, 0.3],
  ['syn', 7, 6, 0.10, 11, 1000, 1]
];
const out = [];
let realU = null;
for (const [kind, seed, blockIdx, frac, maskSeed, r, g] of SCENARIOS) {
  let U, CS;
  if (kind === 'real') { B.setReal(); U = realU = realU || decode(); CS = B.computeCS(); }
  else { B.setSyn(); const d = B.genData(seed); U = d.U; CS = d.CS; }
  const T = B.T;
  const { M, frac: effFrac } = B.buildBlockMask(B.BLOCKS[blockIdx].s, frac, maskSeed);
  const stl = B.stmacJoint(U, M, Lg, r, g, true, B.MDV_WIN);
  const pt = B.pureTemporal(U, M, B.AT);
  const stt = B.stmacJoint(U, M, Lg, r, g, false, B.MDV_WIN);
  const mdv = B.climFill(U, M, stl.C);
  const s0 = B.stmacJoint(U, M, Lg, 10, 0, true, B.MDV_WIN, true);
  const flat = R => { const o = new Float64Array(B.N * T); R.forEach((x, v) => o.set(x, v * T)); return o; };
  out.push({ kind, seed, blockIdx, frac, maskSeed, r, g, T, effFrac, n: stl.n, bw: stl.bw,
    rPT: B.rmseMasked(U, CS, pt, M), rMDV: B.rmseMasked(U, CS, mdv, M),
    rSTL: B.rmseMasked(U, CS, stl.R, M), rSTT: B.rmseMasked(U, CS, stt.R, M), rS0: B.rmseMasked(U, CS, s0.R, M),
    checksum: reconChecksum([flat(stl.R), flat(pt), flat(stt.R), flat(mdv), flat(s0.R)], B.N, T) });
  console.log(kind, blockIdx, 'STMAC', out[out.length - 1].rSTL.toFixed(4), 'S0', out[out.length - 1].rS0.toFixed(4));
}
const file = path.join(TESTS_DIR, 'reference/solver-reference.json');
fs.writeFileSync(file, JSON.stringify({
  source: 'inline solver of the single-file index.html at commit 473edc3, with the patches listed in reference/single-file-solver.js',
  engine: 'node ' + process.versions.node + ', V8 ' + process.versions.v8,
  note: 'full double precision. Other JavaScript engines may differ in the last bit (Math functions), so snapshot checks use a 1e-12 relative tolerance; exact old-vs-new checks run both solvers in the same engine (differential.js).',
  scoring: 'unobserved cells at clock hours 8 to 16 inclusive (08:00-16:55 local time)',
  dataSha256,
  scenarios: out
}, null, 1) + '\n');
console.log('wrote', path.relative(process.cwd(), file), out.length, 'scenarios');
