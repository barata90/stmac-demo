/* Build tests/reference/solver-reference.json from the ORIGINAL single-file page, so the
 * refactored solver is always checked against the code that produced the published demo.
 *
 * Usage (from tests/):
 *   git show 473edc3:index.html > /tmp/stmac-single-file.html
 *   node tools/make-reference.mjs /tmp/stmac-single-file.html
 *
 * The script evaluates the inline solver of that page in a sandbox and records, for each
 * scenario, the four RMSEs, the unknown count, the half-bandwidth, the effective missing
 * fraction and a sampled checksum over every reconstruction array. It also writes
 * reference/single-file-solver.js: the same solver section with the base64 payload removed,
 * which the differential tests run next to the refactored core in the same engine. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { TESTS_DIR, reconChecksum } from '../helpers.mjs';

const src = process.argv[2];
if (!src) { console.error('usage: node tools/make-reference.mjs <single-file index.html>'); process.exit(2); }
const html = fs.readFileSync(src, 'utf8');
const js = html.split('<script>')[1].split('</script>')[0];
const a = js.indexOf('/* ================= real 1999 NLR payload');
const b = js.indexOf('/* ================= state ================= */');
if (a < 0 || b < 0) { console.error('could not find the solver section in ' + src); process.exit(1); }
const code = js.slice(a, b) + `
function computeCS(){const CS=[];for(let v=0;v<N;v++){const cs=new Float64Array(T);for(let i=0;i<T;i++)cs[i]=clearSky(v,i);CS.push(cs);}return CS;}
function decodeReal(){const bin=atob(REAL_B64);const u8=new Uint8Array(bin.length);for(let i=0;i<bin.length;i++)u8[i]=bin.charCodeAt(i);
 const dv=new DataView(u8.buffer);const Tr=REALMETA.DAYS*SPD;const U=[];for(let v=0;v<N;v++){const u=new Float64Array(Tr);for(let i=0;i<Tr;i++)u[i]=dv.getInt16((v*Tr+i)*2,true);U.push(u);}return U;}
function setReal(){DAYS=REALMETA.DAYS;T=SPD*DAYS;DOY0=REALMETA.DOY0;START_UTC=REALMETA.START;}
function setSyn(){DAYS=SYN.DAYS;T=SPD*DAYS;DOY0=SYN.DOY0;START_UTC=SYN.START;}
globalThis.__B={buildGraph,buildBlockMask,pureTemporal,stmacJoint,climFill,rmseMasked,genData,computeCS,decodeReal,setReal,setSyn,BLOCKS,MDV_WIN,AT,N,get T(){return T;}};
`;
/* fixture: the solver section without the 590 KB payload, wrapped in a factory */
const solverOnly = js.slice(a, b).replace(/const REAL_B64='[^']*';/, '/* REAL_B64 removed: the tests feed the decoded assets/data/nlr1999.js, whose sha256 matches this payload */');
if (solverOnly.includes('REAL_B64=')) { console.error('payload line not found'); process.exit(1); }
fs.writeFileSync(path.join(TESTS_DIR, 'reference/single-file-solver.js'),
  '/* Solver section of the single-file index.html at commit 473edc3, generated by tools/make-reference.mjs.\n' +
  ' * Do not edit: this is the behaviour the refactored assets/js/stmac-core.js must reproduce. */\n' +
  'function makeSingleFileSolver(){\n\'use strict\';\n' + solverOnly +
  '\nfunction computeCS(){const CS=[];for(let v=0;v<N;v++){const cs=new Float64Array(T);for(let i=0;i<T;i++)cs[i]=clearSky(v,i);CS.push(cs);}return CS;}' +
  '\nfunction setReal(){DAYS=REALMETA.DAYS;T=SPD*DAYS;DOY0=REALMETA.DOY0;START_UTC=REALMETA.START;}' +
  '\nfunction setSyn(){DAYS=SYN.DAYS;T=SPD*DAYS;DOY0=SYN.DOY0;START_UTC=SYN.START;}' +
  '\nreturn {buildGraph,buildBlockMask,pureTemporal,stmacJoint,climFill,rmseMasked,genData,computeCS,setReal,setSyn,BLOCKS,MDV_WIN,AT,N,get T(){return T;}};\n}\n');
const payloadRaw = Buffer.from(js.match(/const REAL_B64='([^']*)'/)[1], 'base64');
const dataSha256 = crypto.createHash('sha256').update(payloadRaw).digest('hex');

const ctx = { atob: s => Buffer.from(s, 'base64').toString('binary') };
vm.createContext(ctx);
vm.runInContext(code, ctx);
const B = ctx.__B;
const { Lg } = B.buildGraph();

/* kind, seed (synthetic weather), block index, outage fraction, mask seed, r, gamma */
const SCENARIOS = [
  ...[0, 1, 2, 3, 4, 5, 6].map(k => ['real', 42, k, 0.10, 11, 1000, 3]),  /* page defaults, every block length */
  ['real', 42, 2, 0.05, 7930, 100, 0],
  ['real', 42, 6, 0.15, 11, 10000, 30],
  ['real', 42, 0, 0.15, 99, 10, 0],
  ['real', 42, 3, 0.05, 12345, 10000, 30],
  ['syn', 42, 3, 0.10, 11, 1000, 3],
  ['syn', 1013904265, 5, 0.12, 7930, 10, 0.3],
  ['syn', 7, 6, 0.10, 11, 1000, 1]
];
const out = [];
for (const [kind, seed, blockIdx, frac, maskSeed, r, g] of SCENARIOS) {
  let U, CS;
  if (kind === 'real') { B.setReal(); U = B.decodeReal(); CS = B.computeCS(); }
  else { B.setSyn(); const d = B.genData(seed); U = d.U; CS = d.CS; }
  const T = B.T;
  const { M, frac: effFrac } = B.buildBlockMask(B.BLOCKS[blockIdx].s, frac, maskSeed);
  const stl = B.stmacJoint(U, M, Lg, r, g, true, B.MDV_WIN);
  const pt = B.pureTemporal(U, M, B.AT);
  const stt = B.stmacJoint(U, M, Lg, r, g, false, B.MDV_WIN);
  const mdv = B.climFill(U, M, stl.C);
  const flat = R => { const o = new Float64Array(B.N * T); R.forEach((x, v) => o.set(x, v * T)); return o; };
  out.push({ kind, seed, blockIdx, frac, maskSeed, r, g, T, effFrac, n: stl.n, bw: stl.bw,
    rPT: B.rmseMasked(U, CS, pt, M), rMDV: B.rmseMasked(U, CS, mdv, M),
    rSTL: B.rmseMasked(U, CS, stl.R, M), rSTT: B.rmseMasked(U, CS, stt.R, M),
    checksum: reconChecksum([flat(stl.R), flat(pt), flat(stt.R), flat(mdv)], B.N, T) });
  console.log(kind, blockIdx, 'STMAC', out[out.length - 1].rSTL.toFixed(4));
}
const file = path.join(TESTS_DIR, 'reference/solver-reference.json');
fs.writeFileSync(file, JSON.stringify({
  source: 'inline solver of the single-file index.html at commit 473edc3',
  engine: 'node ' + process.versions.node + ', V8 ' + process.versions.v8,
  note: 'full double precision. Other JavaScript engines may differ in the last bit (Math functions), so snapshot checks use a 1e-12 relative tolerance; exact old-vs-new checks run both solvers in the same engine (differential.js).',
  dataSha256,
  scenarios: out
}, null, 1) + '\n');
console.log('wrote', path.relative(process.cwd(), file), out.length, 'scenarios');
